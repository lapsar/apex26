#!/usr/bin/env python3
"""Разносит старый CLAUDE.md по файлам docs/notes/ БЕЗ правки текста.

Каждый файл = заголовок-пояснение + куски исходника (диапазоны строк, 1-based,
включительно). Диапазоны обязаны покрыть исходник целиком и без пересечений —
скрипт это проверяет, а потом собирает исходник обратно из файлов и сравнивает
побайтово.
"""
import sys, os, collections

SRC = sys.argv[1]
OUT = sys.argv[2]
lines = open(SRC, encoding='utf-8').read().split('\n')
N = len(lines)
if lines[-1] == '':
    N -= 1

# пункты §10: начало -> номер
items = {2079:'1',2087:'2',2091:'3',2116:'4',2223:'5',2225:'6',2226:'7',2227:'8',2228:'9',
         2232:'10',2245:'18',2284:'19',2412:'20',2487:'21',2554:'22',2620:'23',2721:'24',
         2774:'25',2888:'26',2983:'27',3021:'15',3042:'14',3055:'16',3153:'16-old',3163:'16-bis',
         3220:'17',3229:'11',3236:'12',3241:'13'}
starts = sorted(items)
item_rng = {}
for i, s in enumerate(starts):
    e = (starts[i+1]-1) if i+1 < len(starts) else 3312
    item_rng[items[s]] = (s, e)

def its(*names):
    return [item_rng[n] for n in names]

H = lambda title, note: (
    f"# {title}\n\n"
    f"> Перенесено из CLAUDE.md без правки текста (09.2026). Ссылки вида «§4», «§10 п.16»\n"
    f"> указывают на разделы СТАРОГО CLAUDE.md — таблица «где теперь §N» лежит в самом\n"
    f"> CLAUDE.md, раздел «Указатель». {note}\n\n")

FILES = [
 ('game.md', 'Игра: что это, дух, физика, контракт модели болида',
  'Разделы §1, §2, §5, §6.',
  [(1,57),(583,657)]),
 ('performance.md', 'Производительность и бюджет вызовов отрисовки',
  'Раздел §3.', [(58,138)]),
 ('balance.md', 'Баланс: константы, якорь, плотность поля, разброс квалификации',
  'Раздел §4 (без 4-bis).', [(139,375)]),
 ('neutralisation.md', 'Нейтрализация: жёлтые флаги и VSC',
  'Раздел §4-bis.', [(376,582)]),
 ('tracks/overview.md', 'Трассы: общее — таблица, перевод координат, добавление трассы, уроки окружения',
  'Начало §7, «Как добавлять новую трассу», «Новая трасса не должна ломать старые», начало §8 (уроки 1-9), §9-bis.',
  [(658,717),(1083,1129),(1130,1196),(2047,2076)]),
 ('tracks/montreal.md', 'Монреаль', 'Подразделы §7 и §8 про Монреаль.',
  [(718,782),(1319,1485)]),
 ('tracks/miami.md', 'Майами', 'Подразделы §7 и §8 про Майами.',
  [(783,866),(1495,1602)]),
 ('tracks/hungaroring.md', 'Хунгароринг', 'Подразделы §7 и §8 про Хунгароринг.',
  [(867,963),(1603,1620)]),
 ('tracks/monza-silverstone.md', 'Монца и Сильверстоун: оговорки разметки',
  'Подразделы §8 про Монцу и Сильверстоун.', [(1305,1318),(1486,1494)]),
 ('sources.md', 'Источники данных: TUMFTM, openf1, онбоард-видео, OSM и спутник',
  'Подразделы §7 и §8 про источники.', [(964,1082),(1197,1304)]),
 ('limitations.md', 'Известные ограничения', 'Раздел §9.', [(1621,2046)]),
 ('open-tasks/balance.md', 'Открытые задачи: баланс и потенциал игрока',
  'Пункты §10: 3, 13, 19, 20, 21, 22, 26 (заголовок раздела §10 — здесь же).',
  [(2077,2078)] + its('3','13','19','20','21','22','26')),
 ('open-tasks/race-ai.md', 'Открытые задачи: гонка, ИИ, обгоны, флаги',
  'Пункты §10: 4, 5, 7, 8, 9, 10, 11, 12, 14, 15, 16, 16-old, 16-bis, 17, 18, 23.',
  its('4','5','7','8','9','10','11','12','14','15','16','16-old','16-bis','17','18','23')),
 ('open-tasks/tracks.md', 'Открытые задачи: трассы и окружение',
  'Пункты §10: 1, 2, 6, 24, 25, 27.', its('1','2','6','24','25','27')),
 ('journal/v1.16.md', 'Журнал: v1.16.x', 'Часть §11, новые записи сверху.', [(3313,3564)]),
 ('journal/v1.15.80-99.md', 'Журнал: v1.15.80 — v1.15.99', 'Часть §11, новые записи сверху.', [(3565,4599)]),
 ('journal/v1.15.66-79.md', 'Журнал: v1.15.66 — v1.15.79', 'Часть §11, новые записи сверху.', [(4600,5305)]),
 ('journal/v1.15.50-65.md', 'Журнал: v1.15.50 — v1.15.65', 'Часть §11, новые записи сверху.', [(5306,6038)]),
 ('journal/v1.15.17-49.md', 'Журнал: v1.15.17 — v1.15.49 и ранее', 'Часть §11, новые записи сверху.', [(6039,6599)]),
 ('owner.md', 'Как работать с владельцем и как вести записи', 'Разделы §12 и §15.',
  [(6600,6640),(7216,N)]),
 ('checklist.md', 'Регрессионный чек-лист (полная версия)', 'Раздел §13.', [(6641,6811)]),
 ('repo.md', 'Что лежит в репозитории (полное дерево)', 'Раздел §14.', [(6812,7215)]),
]

# 1. покрытие без дыр и пересечений
cov = collections.Counter()
for _,_,_,rs in FILES:
    for a,b in rs:
        for k in range(a,b+1): cov[k]+=1
bad = [k for k in range(1,N+1) if cov[k]!=1] + [k for k in cov if k>N or k<1]
assert not bad, f'покрытие нарушено: {bad[:20]}'

# 2. запись
os.makedirs(OUT, exist_ok=True)
for name,title,note,rs in FILES:
    p = os.path.join(OUT,name); os.makedirs(os.path.dirname(p), exist_ok=True)
    body = []
    for a,b in rs:
        body.append('\n'.join(lines[a-1:b]))
    with open(p,'w',encoding='utf-8') as f:
        f.write(H(title,note) + '\n\n'.join(body) + '\n')

# 3. обратная сборка: по диапазонам достаём куски из ФАЙЛОВ и кладём на свои места
rebuilt = [None]*(N+1)
for name,title,note,rs in FILES:
    txt = open(os.path.join(OUT,name),encoding='utf-8').read()
    hdr = H(title,note)
    assert txt.startswith(hdr)
    rest = txt[len(hdr):]
    assert rest.endswith('\n'); rest = rest[:-1]
    parts = rest.split('\n\n')
    # куски склеены через пустую строку; восстанавливаем по длинам
    pos = 0; flat = rest.split('\n')
    for a,b in rs:
        n = b-a+1
        chunk = flat[pos:pos+n]
        for i,l in enumerate(chunk): rebuilt[a+i] = l
        pos += n
        if pos < len(flat):
            assert flat[pos] == '', (name, a, b)
            pos += 1
    assert pos == len(flat), name
orig = lines[:N]
assert rebuilt[1:] == orig, 'обратная сборка разошлась с исходником'
print(f'ОК: {N} строк, {len(FILES)} файлов, сборка совпала с исходником побайтово')
