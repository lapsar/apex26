/* ============================================================================
   Пробник 14 — ОБГОНЫ СОПЕРНИКОВ ДРУГ ДРУГА

   Считает, сколько раз болиды ИИ реально меняются местами между собой за круг
   гонки. Обгоном считается переход из «на 6.04 м позади» в «на 6.04 м впереди»
   — длина корпуса; машины, едущие борт в борт, меняются местами в протоколе
   на сантиметрах, и это не обгон.

   ЗАЧЕМ. Владелец заметил (08.2026), что внутри пелотона стало меньше борьбы,
   чем было раньше. Замер подтвердил: на Монреале обгонов было ~24 за гонку
   в v1.15.24 и ~4 в v1.15.35. Причина нашлась двоичным поиском по архиву —
   одна строка из v1.15.26, где `ovLock` защёлкивался на любом болиде, который
   в зоне торможения ВЫГЛЯДЕЛ стоящим (порог считался от МОЕГО темпа в МОЕЙ
   точке трассы), и через две секунды после старта поле выстраивалось в колонну.
   Двенадцать сборок этого никто не видел, потому что обгоны никто не считал.

   Порог здесь намеренно грубый: он ловит обвал в разы, а не дрожание в 20 %.
   Сравнивать надо не с абсолютом, а с эталоном ниже: если числа поехали вниз
   на всех трассах сразу — правка задела перестроение соперников.
   ========================================================================== */
'use strict';

const H = require('./harness');
const R = require('./report');

// снято на v1.15.45 (1 круг, режим Норма, игрок 11-м, зёрна 7/91/13)
// было на v1.15.38: Monza 81, Silverstone 41, Montreal 55 — числа выросли вдвое-втрое
// намеренно, когда обгон научился доводиться до конца (защёлка цели, см. DUEL_EDGE)
const REF = { Monza: 162, Silverstone: 150, Montreal: 99 };
const FLOOR = 25;               // на трассу за три зерна; v1.15.35 давал на Монреале 16

function run(opt) {
  opt = opt || {};
  const r = R.result('Обгоны соперников друг друга — пелотон не выстраивается в колонну');
  const seeds = opt.seeds ? String(opt.seeds).split(',').map(Number) : [7, 91, 13];
  let total = 0;

  for (const T of H.tracks(true)) {
    const per = [];
    for (const seed of seeds) {
      const env = H.loadGame({ seed });
      H.setupWeekend(env, { trackIdx: T.idx, diff: opt.diff || 'normal', laps: 1 });
      H.startRaceAt(env, 11);
      H.lightsOut(env);
      H.noRetirements(env);          // сход убрал бы болид из счёта и добавил шума
      per.push(env.evalIn(`(function(){
        var dt=1/60, st={}, K=function(a,b){return a+'|'+b;}, n=0;
        for(var a=0;a<field.length;a++)for(var b=a+1;b<field.length;b++)
          st[K(a,b)] = field[a].dist-field[b].dist>0 ? 1 : -1;
        __drive(Math.round(300/dt),dt,'auto',function(){
          for(var a=0;a<field.length;a++)for(var b=a+1;b<field.length;b++){
            var d=field[a].dist-field[b].dist, k=K(a,b);
            if(st[k]>0&&d<-6.04){st[k]=-1;n++;}
            else if(st[k]<0&&d>6.04){st[k]=1;n++;}}
          return !(phase===''||raceOver);});
        return n;})()`));
    }
    const sum = per.reduce((a, b) => a + b, 0);
    total += sum;
    const ref = REF[T.name];
    r.line(`${T.name.padEnd(12)} обгонов ИИ-ИИ за круг по зёрнам: ${per.join(', ')} · всего ${sum}`
      + (ref === undefined ? ' · эталона нет (новая трасса)' : ` · эталон ${ref}`));
    if (sum < FLOOR) r.fail(`${T.name}: соперники обогнали друг друга ${sum} раз за ${seeds.length} заезда`
      + ` при пороге ${FLOOR}${ref === undefined ? '' : ` и эталоне ${ref}`} — пелотон встал в колонну`);
  }

  r.line(`всего по видимым трассам ${total} (эталон ${Object.values(REF).reduce((a, b) => a + b, 0)})`);
  r.note('порог грубый: ловит обвал в разы. Числа новой трассы печатаются заметкой — перенести их в REF');
  r.note('обгоны идут в основном в первые 30 с, пока поле разбирается с решётки; дальше темп ИИ детерминирован');
  return r;
}

module.exports = { run };
if (require.main === module) R.main(run);
