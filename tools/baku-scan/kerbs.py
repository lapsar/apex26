#!/usr/bin/env python3
"""Поребрики и краска у кромки Баку по онбоарду поула 2026 (v1.17.11, владелец 25.10.2026: «проедь весь круг и сравни углы и зоны вылета
с онбоардом; где на асфальте цветные поребрики или зоны — сделай так же»). Общее правило игры ставит поребрик внутри КАЖДОГО поворота
круче R 20 м — у Баку это 27 кусков (полоски на изгибах главной прямой, в замке, на Нефтчиляр), а на онбоарде их 9, и два из них —
СНАРУЖИ (подход к T1, выход T16), где правило их не ставит. Ключ `kerbs` задаёт куски целиком; ключ `stripes` — краска у кромки,
`verge:true` — краска ложится и на метровую обочину до стены (зелёные велодорожки и зебры у стены, красные поля за поребриками).
S — по кадрам онбоарда (kadry.tsv), в счёте v1.17.14 (после сглаживания поворотов; прежние -> новые — s-v1.17.13.tsv), latLon — по az-center.geojson. Строки — в SCENERY_BAKU (повторный запуск заменяет блоки).
    python3 kerbs.py [index.html]"""
import os, re, sys
os.environ['BK_GEOJSON'] = 'az-center.geojson'
import bk
HTML = sys.argv[1] if len(sys.argv) > 1 else '../../index.html'
ll = lambda S: [round(v, 6) for v in bk.latlon(*bk.at(S)[0])]
KERBS = [   # сторона, S от, S до, кадры
    ('R', 94, 168, 'k23–k29, k434–k437: подход к T1 — полосатый поребрик вдоль правой кромки, за ним светлая полоса и стена Qatar Airways'),
    ('R', 1610, 1642, 'k132–k135: апекс T4'),
    ('R', 1992, 2026, 'k168–k172: апекс T6, за ним красное поле с логотипом aws'),
    ('R', 2378, 2412, 'k201–k205: апекс T7'),
    ('L', 2590, 2606, 'k225–k227: короткий поребрик в апексе T8, вокруг зелёная краска'),
    ('L', 2734, 2768, 'k243–k245: апекс T12, за ним зелёная краска с белой «зеброй»'),
    ('L', 3589, 3615, 'k298–k300: апекс T15 (малиновое поле за ним не поместилось: изнутри угол дома Venesiya в 2 м за стеной)'),
    ('L', 3924, 3974, 'k327–k330: апекс T16, за ним красное поле (v1.17.10)'),
    ('R', 3986, 4042, 'k333–k338: выход T16 — длинный поребрик снаружи, за ним голубая полоса American Express'),
]
GREEN = '#2e6b5f'   # медиана зелёной краски по кадрам k132, k225–k227, k245, k271: #2e6a5c…#37625a
STRIPES = [   # corner, сторона, S от, S до, ширина от кромки, цвет, verge, кадры
    ('T4', 'L', 1591, 1617, 2.5, GREEN, 1, 'k131–k132: перед T4 у левой стены зелёная полоса с «зеброй»'),
    ('T6', 'R', 1994, 2024, 4, '#b0262c', 1, 'k168–k172: за поребриком апекса красное поле'),
    ('T8', 'L', 2582, 2688, 2.5, GREEN, 1, 'k225–k235: зелёная краска в апексе T8 и велодорожка вдоль крепостной стены в замке'),
    ('up', 'L', 2706, 2740, 3, '#1f5c98', 1, 'k238–k242 (v1.17.14): подъём — за белой линией синяя краска salesforce с белыми буквами до барьера'),
    ('T12', 'L', 2742, 2778, 3, GREEN, 1, 'k244–k245: за поребриком апекса зелёное поле'),
    ('T13', 'L', 3132, 3184, 2.5, GREEN, 1, 'k270–k273: у левой стены зелёная полоса с «зеброй»'),
    ('T16i', 'L', 3928, 3978, 4, '#b0262c', 0, 'кадры 326–330: за поребриком апекса — красное поле (v1.17.10)'),
    ('T16x', 'R', 3986, 4042, 1.2, '#40a0b1', 1, 'k333–k338: за поребриком выхода голубая полоса American Express'),
]
rk = ["    {side:'%s', fromS:%d, toS:%d, fromLatLon:[%.6f,%.6f], toLatLon:[%.6f,%.6f]},   // %s" % (sd, a, b, *ll(a), *ll(b), why) for sd, a, b, why in KERBS]
rs = ["    {corner:'%s', fromS:%d, toS:%d, side:'%s', width:%g, color:'%s',%s fromLatLon:[%.6f,%.6f], toLatLon:[%.6f,%.6f]},   // %s"
      % (c, a, b, sd, w, col, ' verge:true,' if v else '', *ll(a), *ll(b), why) for c, sd, a, b, w, col, v, why in STRIPES]
KB = ("  /* Поребрики по онбоарду (v1.17.11, tools/baku-scan/kerbs.py): ключ задаёт куски целиком вместо правила «внутри каждого поворота». */\n"
      "  kerbs: [\n" + "\n".join(rk) + "\n  ],\n")
SB = ("  stripes: [   // краска у кромки (v1.17.10–11): width — от кромки полотна, цвет — как на экране; verge — и на обочину до стены\n" + "\n".join(rs) + "\n  ],\n")
s = open(HTML).read(); i = s.index('const SCENERY_BAKU = {'); j = s.index('\n};', i); blk = s[i:j]
blk = re.sub(r"  /\* Поребрики по онбоарду .*?\n  kerbs: \[\n.*?\n  \],\n", '', blk, flags=re.S)
blk = re.sub(r"  stripes: \[.*?\n  \],\n", KB + SB, blk, count=1, flags=re.S)
s = s[:i] + blk + s[j:]; open(HTML, 'w').write(s); print(KB + SB)
