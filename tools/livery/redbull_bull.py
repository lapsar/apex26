def ridge(z):
  for (z0, y0), (z1, y1) in zip(RIDGE, RIDGE[1:]):
    if z1 <= z <= z0: return y0 + (y1 - y0) * (z - z0) / (z1 - z0)
  return RIDGE[0][1] if z > RIDGE[0][0] else RIDGE[-1][1]

