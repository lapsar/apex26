nfade=[7,6,7,5,6]   # сколько столбцов в ряду (сверху вниз — разная длина, как на фото)
for r in range(5):
  y0=0.52+0.055*r;y1=y0+0.055
  for c in range(nfade[r]):
    if (r+c)%2==0:
      z1,z0=cols[c],cols[c+1]
      side.append({"c":"ink","wrap":True,"note":"клетка шахматного флага (ряд %d)"%(r+1),"p":P(sd,[(z0,y1),(z0,y0),(z1,y0),(z1,y1)])})
# TWG (v1.17.41): надпись не рисуем — масса и ритм: три чёрные плитки шириной букв T, W, G и знак TWG (огранённый «камень» с треугольником)
# по фото: на W17 борт понтона красится только выше y 0.40–0.45 (ниже — днище) — плитки y 0.43–0.58 (на фото 0.29–0.53, 19 см) с серебром под ними, на 12 см вперёд, и с переносом на вид сверху
import os
