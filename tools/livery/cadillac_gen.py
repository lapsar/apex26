side.append({"c":"ink","wrap":True,"note":"знак TWG: треугольник внутри","line":P(sd,[(0.255,0.585),(0.215,0.505),(0.295,0.505),(0.255,0.585)]),"w":4.5})
side.append({"c":"silver","note":"белая панель на щитке заднего крыла (место IFS)","p":P(sd,[(-1.765,1.02),(-2.33,1.02),(-2.33,0.77),(-1.78,0.77)])})
# ---- сверху
top.append({"c":"silver","note":"серебро сверху: нос, кокпит, верх понтона до |x| 0.64 (край понтона — чёрный, как подрез), капот до чёрного хвоста; хвост капота (|x| < 0.30) чёрный с z −0.86, плечи — серебро до z −1.30",
  "p":P(tp,[(3.4,0.0),(3.4,0.30),(1.9,0.30),(0.60,0.64),(-0.90,0.64),(-1.30,0.45),(-1.30,0.30),(-0.86,0.30),(-0.86,0.0)])})
top.append({"c":"ink","note":"чёрная панель на носу перед кокпитом (место телеком-спонсора, на фото — переход в белое к номеру)","p":P(tp,[(1.30,0.0),(1.30,0.35),(0.60,0.35),(0.60,0.0)])})
for r,(z0,z1) in enumerate([(1.30,1.36),(1.36,1.42),(1.42,1.48)]):   # растворение панели клетками к номеру
  for c in range(4):
    if (r+c)%2==1:
      x0,x1=c*0.05,(c+1)*0.05
      if r==2 and c>1:continue
      top.append({"c":"ink","note":"клетка растворения чёрной панели к номеру","p":P(tp,[(z1,x0),(z1,x1),(z0,x1),(z0,x0)])})
top.append({"c":"chev","note":"серебряный шеврон «V» на чёрной панели (знак V-серии, как на фото)","line":P(tp,[(0.92,0.24),(1.12,0.0)]),"w":5})
# переднее крыло: шахматка на кончиках закрылков и щитках (|x| 0.45–0.97)
zs=[2.15,2.30,2.45,2.60,2.75,2.90,3.10];xs=[0.45,0.58,0.71,0.84,0.97]
for i in range(len(zs)-1):
  for j in range(len(xs)-1):
    if (i+j)%2==0:top.append({"c":"silver","note":"клетка переднего крыла","p":P(tp,[(zs[i+1],xs[j]),(zs[i+1],xs[j+1]),(zs[i],xs[j+1]),(zs[i],xs[j])])})
cfg={"key":"cadillac","team":"Cadillac","color":"#C6A15B","halo":"#c2c5c8",
 "src":"2026 по 6 фото владельца 05.11.2026 (сбоку — Мехико, отражено, выровнено по ступицам; сверху — мелкое и в перспективе, «фото» — ортоснимок модели; 3/4 спереди и сзади; сбоку смазанное — сверка), стилизация; надписи и логотипы не переносятся",
 "palette":{"carbon":["#16171a",0.15],"silver":["#c2c5c8",0.3],"ink":["#121416",0.15],"chev":["#c2c5c8",0.3]},
 "num":{"w":0.085,"o":0.045,"nose":"#121416","side":"#e4e6e8","hn":0.15,"hs":0.11,"note":"контурные цифры: на серебряном носу чёрные (на фото «11» белое с чёрной обводкой), на чёрном хвосте капота светлые"},
 "base":"carbon","layers":["silver","ink","chev"],
 "top":{"photo":"cadillac/top_model.png","ppm":TP,"cx":TCX,"cy":TCY,"note":"фото сверху мелкое (болид ~240 пикс) и в перспективе: «фото» — ортоснимок модели W17 (ortho.js), фигуры — по фото сверху и 3/4 спереди и сзади","shapes":top},
 "side":{"photo":"cadillac/side.jpg","ppm":SP,"cx":SCX,"cy":SCY,"note":"Мехико, нос вправо — отражено, повёрнуто на 1.19° (ступицы на одной высоте); калибровка по ступицам (база 719 пикс = 3.40 м), силуэт W17 лёг без поправок, нос у Cadillac на фото на ~0.4 м короче модели","shapes":side}}
s=json.dumps(cfg,ensure_ascii=False).replace('{"c"','\n   {"c"')
open(OUT,'w').write(s);print(len(top),len(side))
