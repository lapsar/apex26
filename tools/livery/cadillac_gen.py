tiles=[("G",0.150,-0.040,0.445),("W",-0.060,-0.290,0.437),("T",-0.310,-0.450,0.43)]   # буква, z от, z до, низ y (к корме ниже, как на фото)
for L,za,zb,yb in tiles:
  k=0.03   # наклон низа к корме (как строка на фото)
  q=[(za,yb+0.14),(za,yb),(zb,yb-k*(za-zb)),(zb,yb+0.14-k*(za-zb))]
  if TWG=='A':side.append({"c":"ink","wrap":True,"note":"TWG плиткой «%s» (буквы не рисуем: масса и ритм надписи)"%L,"p":P(sd,q)})
  else:side.append({"c":"ink","wrap":True,"note":"TWG рамкой «%s»"%L,"line":P(sd,q+[q[0]]),"w":5.5})
gem=[(0.34,0.61),(0.17,0.61),(0.14,0.55),(0.255,0.455),(0.37,0.55),(0.34,0.61)]   # знак TWG: «камень», плоский верх, острый низ
