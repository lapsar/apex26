"""Ливрея Cadillac (v1.17.40): фигуры в метрах болида -> tools/livery/cadillac.json (пиксели фото по калибровке вида).
   python3 -I tools/livery/cadillac_gen.py tools/livery/cadillac.json; затем livery.py -> wrap.js -> livery.py (как у всех команд).
   Клетки шахматного флага проще задать сеткой, чем обводить по одной."""
# Генератор tools/livery/cadillac.json: фигуры задаются в метрах болида и переводятся в пиксели фото (калибровка вида).
import json,sys
OUT=sys.argv[1]
