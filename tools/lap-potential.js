/* ============================================================================
   ПОТЕНЦИАЛ КРУГА ИГРОКА — «выигрывается ли эта трасса на этом режиме»

   Считает круг игрока, который едет идеально, и сопоставляет с полем.
   Не пробник: в чек-лист не входит, ничего не заваливает, эталонов не держит.

   КАК СЧИТАЕТСЯ
     1. Гоночная траектория — БЫСТРЕЙШАЯ линия из `raceline.js`. Она и время круга
        по ней считаются там же; здесь только сопоставление с полем.
     2. Соперники — штатной `qualiLapTime` по тем же трассе и режиму, то есть ровно
        тем же расчётом, что и якорь `pole`.

   ЧТО ЗДЕСЬ БЫЛО ДО 09.2026 И ПОЧЕМУ ЭТО СНЯТО
     Линия строилась лапласовым сглаживанием, а оно минимизирует ДЛИНУ, а не время.
     Оговорка «погрешность около ±2.5 с» оказалась вдвое-вдесятеро заниженной: такая
     линия непроходима (радиус круче выкрута колёс) на ВСЕХ пяти трассах — от 3 точек
     на Сильверстоуне до 31 в Монако, — и время по ней выходило на 4-22 с медленнее
     настоящего потенциала. Врал при этом не масштаб, а ПОРЯДОК ТРАСС: справка
     объявляла Канаду самой выигрываемой из открытых, а владелец на устройстве
     выиграл Сильверстоун с P8 с отрывом 15 с и в Канаде с того же места приехал
     вторым. Быстрейшая линия ставит их в его порядке.
     Прежние числа (лапласова линия, действовали по 09.2026): идеальный круг
     Монца 1:25.865, Монреаль 1:14.742, Сильверстоун 1:43.769, Сузука 1:42.850,
     Монако 1:10.842.

   ЧЕГО ОН НЕ УМЕЕТ — читать обязательно
     Это по-прежнему расчёт ОДИНОЧНОГО круга: ни трафика, ни струи, ни того, что
     живой игрок рулит неточно, тормозит раньше и не попадает в апекс до сантиметра.
     Он говорит, на что способна машина на этой геометрии, а не какой круг проедет
     владелец. Авторитет по «проходимо или нет» один — владелец на устройстве.

   Запуск:  node tools/lap-potential.js [--passes=150]
   ========================================================================== */
'use strict';

const H = require('./harness');
const R = require('./report');
const RL = require('./raceline');

/* Полоса, внутри которой расчёт не решает. Прежде она была ±2.5 с и подпиралась
   тем, что линия минимальной кривизны не равна линии минимального времени. Теперь
   линия честно быстрейшая, и вся оставшаяся неопределённость — это разница между
   идеальным кругом и живым игроком, которая заведомо больше. Полоса оставлена
   прежней намеренно: сужать её, не имея чем измерить живого игрока, значило бы
   выдавать точность, которой нет. */
const BAND = 2.5;

function run() {
  const r = R.result('Потенциал круга игрока против поля (справка, не пробник)');
  const passes = +((process.argv.find(x => x.startsWith('--passes=')) || '').split('=')[1] || 0) || undefined;
  for (const T of H.tracks()) {
    const env = H.loadGame();
    H.setupWorld(env, { trackIdx: T.idx });
    env.evalIn(RL.SRC, 'raceline(fns)');
    const chk = env.evalIn('__RL.check()');
    if (chk > 1e-9) r.fail(`${T.name}: закон руля в raceline разошёлся с playerCornerV на ${chk} м/с`);
    const line = RL.solve(env, { passes });
    const g = env.evalIn(`(function(){
      var off=${JSON.stringify(line.off)}, P=__RL.pos(off), M=__RL.M, L=0;
      for(var i=0;i<M;i++){ var a=P[i], b=P[(i+1)%M]; L+=Math.hypot(b.x-a.x,b.z-a.z); }
      var out={len:Math.round(L), diffs:{}};
      ['easy','normal','hard'].forEach(function(d){
        var rows=ROSTER.slice(0,22).map(function(q){ return qualiLapTime(q.skill,d); })
          .sort(function(a,b){return a-b;});
        out.diffs[d]={p1:rows[0], p22:rows[21],
          pos:rows.filter(function(x){return x<${line.raw};}).length+1};});
      return out;})()`);

    r.line(`${T.name.padEnd(12)} идеальный круг ${R.lap(line.raw)} по траектории ${g.len} м`
      + `  (узкий радиус ${line.Rmin.toFixed(1)} м при пределе выкрута ${env.evalIn('TURN_RMIN')})`
      + `${T.hidden ? '  (трасса скрыта)' : ''}`);
    if (line.bad) r.fail(`${T.name}: найденная линия непроходима в ${line.bad} точках — расчёт недостоверен`);
    for (const d of ['easy', 'normal', 'hard']) {
      const e = g.diffs[d], dp = line.raw - e.p1;
      const verdict = dp < -BAND ? 'поул уверенно' : dp < BAND ? 'на грани — решает мастерство' : 'по расчёту не хватает';
      r.line(`    ${d.padEnd(7)} поул ${R.lap(e.p1)} · игрок ${(dp > 0 ? '+' : '') + dp.toFixed(3)} · решётка P${e.pos} · ${verdict}`);
    }
  }
  r.note('линию строит raceline.js — быстрейшая, а не кратчайшая; прежняя лапласова линия была непроходима на всех пяти трассах');
  r.note('это идеальный одиночный круг: ни трафика, ни струи, ни неточного руления. Проверка на устройстве владельцем — единственный авторитет');
  return r;
}

module.exports = { run };
if (require.main === module) R.main(run);
