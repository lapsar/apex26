'use strict';
const fs = require('fs'), path = require('path');
const arg = (k, d) => { const a = process.argv.find(s => s.startsWith('--' + k + '=')); return a ? a.split('=')[1] : d; };
const OUT = arg('out', null); if (!OUT) throw new Error('нужен --out=<файл>');
const ONLY = arg('only', '1,2,3').split(',').map(Number);
const MARGIN = arg('margin', '0.25');      // м зазора при объезде вставшего игрока сверх суммы полуширин
const WIDE = arg('wide', '1') === '1';     // объезжая вставшего игрока, коридор до hw·0.75 (как у ошибки), а не hw·0.62

let src = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8');
function swap(from, to) {
  const n = src.split(from).length - 1;
  if (n !== 1) throw new Error(`образец найден ${n} раз, нужен ровно 1:\n${from}`);
  src = src.replace(from, to);
}

